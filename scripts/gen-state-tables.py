#!/usr/bin/env python3
"""Generate src/state-year-tables.ts from data/state-brackets-<year>.txt (Tax Foundation table lines).

Line format: ST | single: rate%>$min, ... | mfj: rate%>$min, ... | std: $s/$mfj | exempt: personal/couple/dependent
Run from the repository root:  python3 scripts/gen-state-tables.py
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def money(tok: str):
    tok = tok.strip()
    if 'credit' in tok or tok.startswith('n.a') or tok == '':
        return None
    return int(tok.replace('$', '').replace(',', ''))


def brackets(text: str):
    out = [(round(float(r) / 100, 6), int(m.replace(',', ''))) for r, m in re.findall(r'([\d.]+)%>\$([\d,]+)', text)]
    if not out:
        raise ValueError(f'no brackets in {text!r}')
    return out


def parse(year: int):
    rows = {}
    for line in (ROOT / f'data/state-brackets-{year}.txt').read_text().splitlines():
        if not line.strip() or line.startswith('#'):
            continue
        cols = [c.strip() for c in line.split('|')]
        code = cols[0]
        single = brackets(cols[1].split(':', 1)[1])
        mfj = brackets(cols[2].split(':', 1)[1])
        std = [money(x) for x in cols[3].split(':', 1)[1].split('/')]
        ex = [money(x) for x in cols[4].split(':', 1)[1].split('/')]
        rows[code] = {'single': single, 'mfj': mfj, 'std': std if all(v is not None for v in std) else None,
                      'personal': ex[0], 'dependent': ex[2]}
    return rows


def ts_brackets(bs):
    return '[' + ', '.join(f'[{r}, {m}]' for r, m in bs) + ']'


def main():
    years = sorted(int(p.stem.split('-')[-1]) for p in (ROOT / 'data').glob('state-brackets-*.txt'))
    lines = [
        '// GENERATED by scripts/gen-state-tables.py from data/state-brackets-<year>.txt — do not edit by hand.',
        '// Source: Tax Foundation annual "State Individual Income Tax Rates and Brackets" tables (see the data files',
        '// for URLs and the later-enacted laws applied on top).',
        '',
        '/** [rate, bracket start] pairs; the last bracket has no top. */',
        'export type BracketPairs = Array<[number, number]>;',
        'export interface StateYearRow {',
        '  single: BracketPairs;',
        '  mfj: BracketPairs;',
        '  /** [single, married filing jointly] standard deduction, when the state has one in dollars. */',
        '  std?: [number, number];',
        '  personal?: number;',
        '  dependent?: number;',
        '}',
        '',
        'export const STATE_YEAR_TABLES: Record<number, Record<string, StateYearRow>> = {',
    ]
    for y in years:
        lines.append(f'  {y}: {{')
        for code, r in parse(y).items():
            parts = [f'single: {ts_brackets(r["single"])}', f'mfj: {ts_brackets(r["mfj"])}']
            if r['std']:
                parts.append(f'std: [{r["std"][0]}, {r["std"][1]}]')
            if r['personal'] is not None:
                parts.append(f'personal: {r["personal"]}')
            if r['dependent'] is not None:
                parts.append(f'dependent: {r["dependent"]}')
            lines.append(f'    {code}: {{ {", ".join(parts)} }},')
        lines.append('  },')
    lines.append('};')
    (ROOT / 'src/state-year-tables.ts').write_text('\n'.join(lines) + '\n')
    print(f'wrote src/state-year-tables.ts for {years}')


if __name__ == '__main__':
    sys.exit(main())
